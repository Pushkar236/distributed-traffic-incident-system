"""Function code deployed on the local FaaS platform (gateway/faas.py).

Rules a function follows (as on AWS Lambda / Cloudflare Workers / Azure Functions):
    * stateless   - everything it needs arrives in `event`, everything it produces is returned
    * short-lived - runs for milliseconds, then the instance may be frozen or destroyed
    * no I/O to platform services - storing the result (e.g. in the DFS) is done by the
      platform's output binding, not by the function itself
This module is imported inside separate worker processes, so it only uses the standard library.
"""
import os
import time
from datetime import datetime

SEVERITY_SCORE = {"High": 60, "Medium": 35, "Low": 10}
TYPE_SCORE = {"Accident": 25, "Road Blockage": 20, "Traffic Signal Failure": 15,
              "Heavy Congestion": 10, "Vehicle Breakdown": 8}


def init():
    """Runs once per new instance (the 'init phase' of a cold start)."""
    return {"pid": os.getpid(), "started": time.time()}


def classify_incident(event):
    """Event-triggered on INCIDENT_CREATED: priority score + recommended actions."""
    inc = event["incident"]
    score = SEVERITY_SCORE.get(inc.get("severity"), 0) + TYPE_SCORE.get(inc.get("type"), 0)
    hour = datetime.now().hour
    if hour in (8, 9, 10, 17, 18, 19, 20):
        score += 10                                    # peak hour
    priority = "P1" if score >= 75 else "P2" if score >= 45 else "P3"
    actions = {"P1": ["pre-empt signals on the response corridor", "notify neighbouring regions",
                      "push variable-message-sign alert"],
               "P2": ["dispatch nearest unit", "update traffic advisory"],
               "P3": ["monitor via cameras"]}[priority]
    return {"incident_id": inc.get("incident_id"), "priority": priority, "score": score,
            "sla_minutes": {"P1": 10, "P2": 20, "P3": 60}[priority], "actions": actions}


def incident_report(event):
    """Event-triggered on RESOLVED (or via HTTP): render a plain-text incident report."""
    inc = event["incident"]
    units = ", ".join(f"{u['unit_id']} ({u['node_id']})" for u in inc.get("assigned_units", [])) or "none"
    lines = [
        "DISTRIBUTED TRAFFIC INCIDENT REPORT",
        "=" * 36,
        f"Incident ID : {inc.get('incident_id')}",
        f"Type        : {inc.get('type')}",
        f"Severity    : {inc.get('severity')}",
        f"Location    : {inc.get('location')}",
        f"Description : {inc.get('description') or '-'}",
        f"Detected by : {inc.get('detected_by')}",
        f"Handled by  : {inc.get('handled_by')}",
        f"Status      : {inc.get('status')}",
        f"Units       : {units}",
        f"Created     : {inc.get('created_at')}",
        f"Last update : {inc.get('updated_at')}",
        "",
        f"Generated by FaaS function incident_report at {datetime.now().isoformat(timespec='seconds')}",
        "Stored in the FA-2 distributed file system (chunked, replicated).",
    ]
    return {"path": f"/reports/{inc.get('incident_id')}.txt", "content": "\n".join(lines) + "\n"}


def congestion_advisory(event):
    """HTTP-triggered: turn per-region density readings into advisories."""
    advisories = []
    for region in event.get("traffic", []):
        for seg in region.get("segments", []):
            if seg["density"] >= 75:
                advisories.append(f"{region['node_id']}: avoid {seg['road']} ({seg['density']:.0f}% density)")
    return {"advisories": advisories or ["traffic normal on all monitored roads"], "regions": len(event.get("traffic", []))}


FUNCTIONS = {"classify_incident": classify_incident, "incident_report": incident_report,
             "congestion_advisory": congestion_advisory}


def run(name, event):
    """Entry point executed inside the worker process."""
    started = time.perf_counter()
    result = FUNCTIONS[name](event)
    return {"result": result, "pid": os.getpid(), "handler_ms": round((time.perf_counter() - started) * 1000, 3)}
